package search

import "testing"

// 用真实抓脏数据验证清洗效果：模拟 StripHTML 后的腾讯校招页，
// 导航碎片、营销文案与 JD 正文混在一起，且正文被换行切断。
func TestCleanJDTextRealWorldTencent(t *testing.T) {
	dirty := `# 岗位详情 | 腾讯校招
# 腾讯校园招聘
首页
青云计划
岗位投递
招聘动态
了解腾讯
求职攻略
登录
你是腾讯产品「背后」的英雄，
打造出更稳定安全、高效可靠的后台支撑体系，
守护海量用户的笑容！
* 岗位描述
负责实现和优化公司的产品功能，以及构建和维护关键服务与基础设施。
1、深入理解业务需求和产品设计，高效地实现并优化产品功能；
2、持续优化架构，提升关键服务和基础设施的稳定性与可用性；
了解更多
加入腾讯的"N个理由"
关心成长
腾讯注重人才培养，有完善的导师制度
立即申请
版权所有`

	got := CleanJDText(dirty)

	t.Logf("清洗结果:\n%s", got)

	// 噪声必须被剔除。
	for _, noise := range []string{
		"首页", "岗位投递", "招聘动态", "求职攻略", "登录",
		"了解更多", "加入腾讯", "关心成长", "立即申请", "版权所有",
		"腾讯校园招聘",
	} {
		if contains(got, noise) {
			t.Errorf("噪声未剔除: %q\n清洗结果: %s", noise, got)
		}
	}

	// JD 正文必须保留。
	for _, keep := range []string{
		"你是腾讯产品「背后」的英雄",
		"负责实现和优化公司的产品功能",
		"深入理解业务需求和产品设计",
		"持续优化架构",
	} {
		if !contains(got, keep) {
			t.Errorf("正文丢失: %q\n清洗结果: %s", keep, got)
		}
	}

	// 被换行切断的中文句子必须合并为连贯文本。
	if contains(got, "你是腾讯产品「背后」的英雄，\n打造出") {
		t.Errorf("被换行切断的句子未合并:\n%s", got)
	}
	if !contains(got, "你是腾讯产品「背后」的英雄，打造出更稳定安全") {
		t.Errorf("段落未正确合并，期望连贯文本，实际:\n%s", got)
	}

	// 列表项应保持独立行。
	if !contains(got, "1、深入理解业务需求和产品设计") {
		t.Errorf("列表项应保留，实际:\n%s", got)
	}
}
